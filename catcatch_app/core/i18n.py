_language_listeners = []

def register_language_listener(callback):
    if callback not in _language_listeners:
        _language_listeners.append(callback)

def get_current_language():
    return config.get("language", "zh_CN")

def set_current_language(code):
    if code in TRANSLATIONS:
        config.set("language", code)
        for cb in _language_listeners:
            try:
                cb(code)
            except Exception:
                pass

def t(key, default="", **kwargs):
    cur = get_current_language()
    d = TRANSLATIONS.get(cur, TRANSLATIONS.get("zh_CN", {}))
    val = d.get(key)
    if val is None:
        val = TRANSLATIONS.get("zh_CN", {}).get(key, default or key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val
