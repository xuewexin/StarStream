_LISTENERS = []

def register_language_listener(callback):
    """注册语言改变时的刷新回调"""
    if callback not in _LISTENERS:
        _LISTENERS.append(callback)

def unregister_language_listener(callback):
    if callback in _LISTENERS:
        _LISTENERS.remove(callback)

def get_current_language():
    """获取当前配置语言代码"""
    return config.get("language", "zh_CN")

def set_current_language(code):
    """设置语言并通知所有界面刷新"""
    if code in TRANSLATIONS:
        config.set("language", code)
        for cb in list(_LISTENERS):
            try:
                cb(code)
            except Exception as e:
                print(f"[i18n] 语言刷新回调异常: {e}")

def t(key, **kwargs):
    """
    获取指定 key 的翻译文本，自动以 kwargs 格式化
    """
    lang = get_current_language()
    dict_map = TRANSLATIONS.get(lang) or TRANSLATIONS["zh_CN"]
    val = dict_map.get(key)
    if val is None:
        # Fallback to zh_CN, then en_US, then raw key
        val = TRANSLATIONS["zh_CN"].get(key) or TRANSLATIONS["en_US"].get(key) or key
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val
