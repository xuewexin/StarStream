import os
import sys
_ICONS_DIR = os.path.dirname(os.path.abspath(__file__))
_APP_DIR = os.path.dirname(_ICONS_DIR)
_MEI = getattr(sys, '_MEIPASS', '')


def get_app_icon():
    """获取程序官方品牌 Logo QIcon"""
    candidates = [
        os.path.join(_APP_DIR, "resources", "starstream.ico"),
        os.path.join(_APP_DIR, "resources", "starstream_logo.png")
    ]
    if _MEI:
        candidates.insert(0, os.path.join(_MEI, "catcatch_app", "resources", "starstream.ico"))
        candidates.insert(1, os.path.join(_MEI, "catcatch_app", "resources", "starstream_logo.png"))

    for p in candidates:
        if p and os.path.exists(p):
            return QIcon(p)
    return get_icon("download", "#3875f6", 32)


def get_icon(name, color="#a1a1aa", size=20):
    """
    动态生成带有指定颜色和尺寸的高清 QIcon
    """
    svg_template = SVG_ICONS.get(name)
    if not svg_template:
        return QIcon()

    svg_content = svg_template.format(color=color).encode("utf-8")
    renderer = QSvgRenderer(QByteArray(svg_content))

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor("transparent"))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)
